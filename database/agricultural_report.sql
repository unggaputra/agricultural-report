-- ---------------------------------------------------------------------
-- STRUKTUR TABEL
-- ---------------------------------------------------------------------
CREATE TABLE `desa` (
  `id_desa` INT NOT NULL AUTO_INCREMENT,
  `nama_desa` VARCHAR(35) NOT NULL,
  PRIMARY KEY (`id_desa`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `lokasi` (
  `id_lokasi` INT NOT NULL AUTO_INCREMENT,
  `nama_lokasi` VARCHAR(35) NOT NULL,
  `id_desa` INT NOT NULL,
  PRIMARY KEY (`id_lokasi`),
  KEY `id_desa` (`id_desa`),
  CONSTRAINT `lokasi_ibfk_1` FOREIGN KEY (`id_desa`) REFERENCES `desa` (`id_desa`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `petani` (
  `id_petani` INT NOT NULL AUTO_INCREMENT,
  `nama_petani` VARCHAR(50) NOT NULL,
  `no_telepon` VARCHAR(20) NOT NULL,
  PRIMARY KEY (`id_petani`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `lahan` (
  `id_lahan` INT NOT NULL AUTO_INCREMENT,
  `id_petani` INT NOT NULL,
  `id_lokasi` INT NOT NULL,
  `luas` INT NOT NULL COMMENT 'm2',
  PRIMARY KEY (`id_lahan`),
  KEY `id_petani` (`id_petani`),
  KEY `id_lokasi` (`id_lokasi`),
  CONSTRAINT `lahan_ibfk_1` FOREIGN KEY (`id_petani`) REFERENCES `petani` (`id_petani`),
  CONSTRAINT `lahan_ibfk_2` FOREIGN KEY (`id_lokasi`) REFERENCES `lokasi` (`id_lokasi`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `bibit` (
  `id_bibit` INT NOT NULL AUTO_INCREMENT,
  `nama_bibit` VARCHAR(35) NOT NULL,
  `jenis_tanaman` VARCHAR(35) NOT NULL,
  PRIMARY KEY (`id_bibit`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `pupuk` (
  `id_pupuk` INT NOT NULL AUTO_INCREMENT,
  `nama_pupuk` VARCHAR(35) NOT NULL,
  `jenis_pupuk` VARCHAR(35) NOT NULL,
  `kg_per_sak` DECIMAL(5,2) NOT NULL DEFAULT 50,
  PRIMARY KEY (`id_pupuk`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `riwayat_tanam` (
  `id_riwayat_tanam` INT NOT NULL AUTO_INCREMENT,
  `id_lahan` INT NOT NULL,
  `id_bibit` INT NOT NULL,
  `jumlah_bibit_kg` DECIMAL(8,2) NOT NULL,
  `tanggal_tanam` DATE NOT NULL,
  `tanggal_panen` DATE NULL,
  `hasil_kg` INT NULL,
  `musim` ENUM('MT1','MT2','MT3') NULL,
  `status` ENUM('tanam','panen','gagal') NOT NULL DEFAULT 'tanam',
  `alasan_gagal` VARCHAR(100) NULL,
  PRIMARY KEY (`id_riwayat_tanam`),
  KEY `id_lahan` (`id_lahan`),
  KEY `id_bibit` (`id_bibit`),
  KEY `idx_tanggal_tanam` (`tanggal_tanam`),
  CONSTRAINT `riwayat_tanam_ibfk_1` FOREIGN KEY (`id_lahan`) REFERENCES `lahan` (`id_lahan`),
  CONSTRAINT `riwayat_tanam_ibfk_2` FOREIGN KEY (`id_bibit`) REFERENCES `bibit` (`id_bibit`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `riwayat_tanam_pupuk` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `id_riwayat_tanam` INT NOT NULL,
  `id_pupuk` INT NOT NULL,
  `jumlah_kg` DECIMAL(8,2) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `id_riwayat_tanam` (`id_riwayat_tanam`),
  KEY `id_pupuk` (`id_pupuk`),
  CONSTRAINT `rtp_ibfk_1` FOREIGN KEY (`id_riwayat_tanam`) REFERENCES `riwayat_tanam` (`id_riwayat_tanam`) ON DELETE CASCADE,
  CONSTRAINT `rtp_ibfk_2` FOREIGN KEY (`id_pupuk`) REFERENCES `pupuk` (`id_pupuk`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `riwayat_pembelian_pupuk` (
  `id_transaksi` INT NOT NULL AUTO_INCREMENT,
  `id_petani` INT NOT NULL,
  `id_pupuk` INT NOT NULL,
  `tanggal_beli` DATE NOT NULL,
  `jumlah_karung` INT NOT NULL,
  PRIMARY KEY (`id_transaksi`),
  KEY `id_petani` (`id_petani`),
  KEY `id_pupuk` (`id_pupuk`),
  KEY `idx_tanggal_beli` (`tanggal_beli`),
  CONSTRAINT `rpp_ibfk_1` FOREIGN KEY (`id_petani`) REFERENCES `petani` (`id_petani`),
  CONSTRAINT `rpp_ibfk_2` FOREIGN KEY (`id_pupuk`) REFERENCES `pupuk` (`id_pupuk`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

