-- Produktivitas (kg/ha) per tahun, desa, jenis tanaman (hanya yang berhasil panen)
CREATE VIEW `v_produktivitas` AS
SELECT YEAR(rt.tanggal_tanam) AS tahun,
       d.nama_desa,
       b.jenis_tanaman,
       COUNT(*) AS jumlah_tanam,
       ROUND(SUM(l.luas) / 10000, 2) AS luas_ha,
       SUM(rt.hasil_kg) AS hasil_kg,
       ROUND(SUM(rt.hasil_kg) / (SUM(l.luas) / 10000)) AS kg_per_ha
FROM riwayat_tanam rt
JOIN lahan l   ON l.id_lahan = rt.id_lahan
JOIN lokasi lo ON lo.id_lokasi = l.id_lokasi
JOIN desa d    ON d.id_desa = lo.id_desa
JOIN bibit b   ON b.id_bibit = rt.id_bibit
WHERE rt.status = 'panen'
GROUP BY YEAR(rt.tanggal_tanam), d.nama_desa, b.jenis_tanaman;

-- Pupuk dibeli vs dipakai (kg) per tahun
CREATE VIEW `v_pupuk_tahunan` AS
SELECT t.tahun, p.nama_pupuk,
       ROUND(SUM(t.dibeli_kg), 2) AS dibeli_kg,
       ROUND(SUM(t.dipakai_kg), 2) AS dipakai_kg,
       ROUND(SUM(t.dibeli_kg) - SUM(t.dipakai_kg), 2) AS selisih_kg
FROM (
  SELECT YEAR(rp.tanggal_beli) AS tahun, rp.id_pupuk,
         rp.jumlah_karung * pk.kg_per_sak AS dibeli_kg, 0 AS dipakai_kg
  FROM riwayat_pembelian_pupuk rp
  JOIN pupuk pk ON pk.id_pupuk = rp.id_pupuk
  UNION ALL
  SELECT YEAR(rt.tanggal_tanam), rtp.id_pupuk, 0, rtp.jumlah_kg
  FROM riwayat_tanam_pupuk rtp
  JOIN riwayat_tanam rt ON rt.id_riwayat_tanam = rtp.id_riwayat_tanam
) t
JOIN pupuk p ON p.id_pupuk = t.id_pupuk
GROUP BY t.tahun, p.nama_pupuk;

